; ==============================================================================
; COMMODORE 64 SPACE INVADERS - FILE: sprites.asm
; ==============================================================================
; In questo file sono definiti i dati grafici degli Sprite per il chip VIC-II.
; 
; ARCHITETTURA DEGLI SPRITE DEL COMMODORE 64:
; - Ogni sprite standard (Hi-Res monocolore) ha una matrice di 24 pixel in larghezza
;   per 21 pixel in altezza.
; - Ogni riga è larga 24 pixel = 3 byte (8 pixel per byte).
; - 21 righe * 3 byte per riga = 63 byte.
; - Il 64° byte è un byte di padding/riempimento (impostato a $00).
; - Quindi ogni sprite occupa esattamente 64 byte in memoria ($40 in esadecimale).
; 
; ASSEGNAZIONE BLOCCHI A PARTIRE DA $2000 (8192 decimale, Blocco $80):
; - Blocco $80 ($2000): Sprite 0 - Cannone Giocatore (Player Cannon)
; - Blocco $81 ($2040): Sprite 1 - Invasore Tipo 1 (Squid) Frame A
; - Blocco $82 ($2080): Sprite 2 - Invasore Tipo 1 (Squid) Frame B
; - Blocco $83 ($20C0): Sprite 3 - Invasore Tipo 2 (Crab) Frame A
; - Blocco $84 ($2100): Sprite 4 - Invasore Tipo 2 (Crab) Frame B
; - Blocco $85 ($2140): Sprite 5 - Invasore Tipo 3 (Octopus) Frame A
; - Blocco $86 ($2180): Sprite 6 - Invasore Tipo 3 (Octopus) Frame B
; - Blocco $87 ($21C0): Sprite 7 - Disco Volante Misterioso (Mystery UFO)
; - Blocco $88 ($2200): Sprite 8 - Esplosione Aliena / Giocatore
; - Blocco $89 ($2240): Sprite 9 - Raggio Laser Giocatore
; - Blocco $8A ($2280): Sprite 10- Bomba Aliena Zig-Zag
; ==============================================================================

